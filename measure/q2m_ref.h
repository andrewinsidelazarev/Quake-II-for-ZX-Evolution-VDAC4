/*
 * q2m_ref.h — замерочная сборка Quake 2 для VDAC4 (считающий рендер ref_cnt).
 *
 * Подключается ко всем файлам ref_gl ключом /FI. Рендер GL вместо рисования
 * зовёт заглушки q2m_gl.c, а те считают, что получил бы растеризатор ПЛИС:
 * многоугольники, вершины, треугольники и закрашенную площадь в точках.
 * Переменная q2m_cat говорит, к какому виду относится текущее рисование; её
 * ставят вставки в gl_rmain.c, gl_rsurf.c, gl_mesh.c, gl_warp.c.
 */
#ifndef Q2M_REF_H
#define Q2M_REF_H

enum
{
	Q2M_C_WORLD,	/* стены, пол, потолок мира (одним проходом с lightmap) */
	Q2M_C_WARP,		/* непрозрачная вода, лава, слизь (волнистые поверхности) */
	Q2M_C_SKY,		/* небо */
	Q2M_C_ALIAS,	/* модели md2: монстры, оружие в руке, предметы */
	Q2M_C_BMODEL,	/* подвижные части мира: двери, лифты, кнопки */
	Q2M_C_SPRITE,	/* спрайты (взрывы) и пустые модели */
	Q2M_C_PART,		/* частицы */
	Q2M_C_ALPHA,	/* прозрачные поверхности: стекло, прозрачная вода */
	Q2M_C_BLEND,	/* вспышки на весь экран */
	Q2M_C_2D,		/* картинки, буквы, полоса состояния, консоль */
	Q2M_C_N
};

extern int q2m_cat;

void Q2M_RefRegister (void);	/* команда q2m_refstats, q2m_gl.c */
void Q2M_InstallGL (void);		/* считающие функции вместо пустых, q2m_gl.c */

#endif
