// =====================================================================================================
// bz_rdwin.sv — чтение SDRAM для ESP мимо очереди команд (SPEC.md 0.4, «Чтение SDRAM по LINK»).
// =====================================================================================================
//
// ЗАЧЕМ (24.11.2026)
//   ESP32 держит в SDRAM ядра то, что ей нужно редко и понемногу, — кадры анимации моделей md2 (на уровень
//   0,2–1,3 МБ; в PSRAM самой ESP им не хватало места). Пишет она их обычной командой WRITE, а читает
//   так: пишет по LINK адрес (RD_ADDR) и сколько пачек (RD_LEN), ядро копирует эти пачки SDRAM в окно —
//   4 КБ блочной памяти (BSRAM), — и ESP читает окно по LINK, как регистры. Мимо очереди — потому что
//   очередь занята кадром, который ядро ещё рисует: ждать её ESP посреди своего кадра не может.
//
// КАК
//   - go (такт, домен clk): начать копию len пачек с адреса addr (байтовый, младшие 5 бит не смотрятся).
//     Пока копия идёт (busy), новый go не принимается.
//   - Клиент моста SDRAM (sd_bridge): запрос пачки (8 слов = 32 байта) держится до ack — как у всех
//     клиентов; адрес следующей пачки готов заранее в регистре (сумматор не стоит на пути к мосту:
//     домен clk_mem — у предела, 62,3 МГц при нужных 60,75, сборка d). Ответные слова приходят по
//     одному, по порядку (так обещает мост) — пишутся в окно подряд. Последнее слово — busy снимается.
//   - Окно: BSRAM 1024 × 32 бит, два такта: пишет домен clk (ответы моста), читает домен rclk — такт
//     самого LINK (link_sck). fb_link выставляет номер слова за 8 тактов SCK до того, как его отдаст, а
//     BSRAM отвечает к следующему фронту rclk — успевает с запасом. Читать окно, пока busy = 1, нельзя:
//     там смесь старого и нового (ESP ждёт busy = 0, а тот виден ей уже после последней записи).
//   - Метка (tag) у этого клиента своя снаружи: в bz_top — метка загрузок с Evo (те только пишут, это —
//     только читает), ack и слова раскладывает верхний модуль.
module bz_rdwin (
    input  wire        clk,
    input  wire        rst_n,
    // команды (домен clk): регистры LINK RD_ADDR / RD_LEN
    input  wire        go,
    input  wire [22:0] addr,             // байтовый адрес первой пачки
    input  wire [7:0]  len,              // пачек: 1…128 (окно 4 КБ); иное — не начинать
    output reg         busy,
    // клиент моста SDRAM (домен clk)
    output reg         b_req,
    output reg  [20:0] b_addr,           // номер 32-битного слова, кратен 8 (пачка)
    input  wire        b_ack,            // ack именно этого запроса (метку разбирает верх)
    input  wire        b_rd_valid,       // слово ответа именно этого клиента
    input  wire [31:0] b_rd_data,
    // окно (домен rclk)
    input  wire        rclk,
    input  wire [9:0]  raddr,
    output reg  [31:0] rdata
);
    reg [7:0]  left;                     // пачек ещё запросить
    reg [10:0] wi;                       // слов уже в окне
    reg [10:0] need;                     // слов всего (len · 8)

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            busy <= 1'b0; b_req <= 1'b0; b_addr <= 21'd0; left <= 8'd0; wi <= 11'd0; need <= 11'd0;
        end else begin
            if (go && !busy && len != 8'd0 && len <= 8'd128) begin
                busy   <= 1'b1;
                b_req  <= 1'b1;
                b_addr <= {addr[22:5], 3'b000};
                left   <= len;
                wi     <= 11'd0;
                need   <= {len, 3'b000};
            end
            // мост принял запрос пачки: следующая — со следующего адреса (запрос снимается на такт ack
            // сам: мост в такте ack новый запрос не берёт — take = req && !ack)
            if (b_req && b_ack) begin
                b_addr <= b_addr + 21'd8;
                left   <= left - 8'd1;
                if (left == 8'd1)
                    b_req <= 1'b0;
            end
            if (b_rd_valid) begin
                wi <= wi + 11'd1;
                if (wi + 11'd1 == need)
                    busy <= 1'b0;
            end
        end
    end

    // окно: BSRAM с двумя тактами (запись — clk, чтение — rclk)
    reg [31:0] win [0:1023];
    always @(posedge clk)
        if (b_rd_valid)
            win[wi[9:0]] <= b_rd_data;
    always @(posedge rclk)
        rdata <= win[raddr];
endmodule
