// =====================================================================================================
// bz_div.sv — последовательный делитель целых чисел без знака: quot = floor(num / den).
// =====================================================================================================
//
// ЗАЧЕМ ОН АДАПТЕРУ
//   Деление в «бомж-3D» нужно в двух местах (gpu/SPEC.md):
//     1) край многоугольника: в какой точке строки начинается ребро — ceil(N / (16·dy));
//     2) перспектива: на концах каждого куска строки из 16 точек — w = floor(2^46 / zi), где zi = 1/z.
//   Результат обязан совпасть с C-моделью до последнего бита, поэтому деление точное, «школьное», без
//   таблиц и приближений.
//
// КАК ДЕЛЯТ В СТОЛБИК В ДВОИЧНОЙ СИСТЕМЕ
//   Так же, как на бумаге, только цифры — 0 и 1, и каждая цифра частного — ответ на вопрос «влезает
//   ли делитель в текущий остаток?». Пример: 13 / 3, то есть 1101 / 11.
//     остаток 0, берём старший бит делимого: 1      — 1 < 3,  цифра частного 0
//     остаток 1, дописываем следующий бит:   11 = 3 — 3 ≥ 3,  цифра 1, остаток 3 − 3 = 0
//     остаток 0, дописываем бит:             0      — 0 < 3,  цифра 0
//     остаток 0, дописываем бит:             1      — 1 < 3,  цифра 0
//   Частное 0100 = 4, остаток 1. Верно: 13 = 4·3 + 1.
//   Один шаг — сдвиг остатка влево с новым битом делимого и одно вычитание. W бит частного — W
//   тактов. Такой делитель занимает мало логики (одно вычитание на WD+1 бит), но работает долго.
//
// ПОЧЕМУ ДОЛГО — ЭТО НОРМАЛЬНО (пока)
//   Ядро этапа A ждёт делитель (48 тактов на деление) — оно образец, а не скорость. В быстром ядре
//   (этап B) делителей будет два, и каждый будет брать по 2 бита за такт (radix-4): деление на конце
//   куска успеет за 16 тактов, пока рисуются 16 точек предыдущего куска.
//
// КАК ПОЛЬЗОВАТЬСЯ (протокол)
//   1) Подать num и den и на один такт start = 1.
//   2) Через W тактов на один такт done = 1, частное — в quot, остаток — в rem (держатся до следующего
//      start). Остаток нужен растеризатору: из него начинается шаг края ребра по строкам (DDA).
//   busy = 1, пока идёт деление. Деление на 0 даёт частное из одних единиц (так устроена схема);
//   ядро на 0 не делит.
module bz_div #(
    parameter W  = 48,           // разрядов делимого и частного
    parameter WD = 32            // разрядов делителя
) (
    input  wire          clk,
    input  wire          rst,
    input  wire          start,
    input  wire [W-1:0]  num,
    input  wire [WD-1:0] den,
    output reg           busy,
    output reg           done,
    output reg  [W-1:0]  quot,
    output reg  [WD-1:0] rem             // остаток: num = quot·den + rem, 0 ≤ rem < den
);
    // q — делимое, которое сдвигается влево: сверху из него «выталкиваются» биты в остаток, а снизу
    // освободившиеся места заполняются цифрами частного. Через W шагов в q лежит частное целиком.
    reg [W-1:0]  q;
    reg [WD:0]   r;              // остаток: на бит шире делителя (после сдвига может стать до 2·den)
    reg [WD-1:0] d;              // делитель, защёлкнутый на start
    reg [$clog2(W+1)-1:0] cnt;   // сколько шагов осталось

    // один шаг деления — чистая комбинационная логика (провода, без триггеров):
    wire [WD:0] r_sh  = {r[WD-1:0], q[W-1]};      // остаток × 2 + следующий бит делимого
    wire [WD:0] r_sub = r_sh - {1'b0, d};         // пробуем вычесть делитель
    wire        ge    = !r_sub[WD];               // старший бит 0 — разность не отрицательна: влезает

    always @(posedge clk) begin
        done <= 1'b0;                             // done — импульс в один такт
        if (rst) begin
            busy <= 1'b0;
            cnt  <= 0;
        end else if (start) begin
            busy <= 1'b1;
            q    <= num;
            d    <= den;
            r    <= 0;
            cnt  <= W[$clog2(W+1)-1:0];
        end else if (busy) begin
            r   <= ge ? r_sub : r_sh;             // влез — остаток уменьшился, нет — просто сдвинут
            q   <= {q[W-2:0], ge};                // очередная цифра частного — снизу
            cnt <= cnt - 1'b1;
            if (cnt == 1) begin                   // это был последний шаг
                busy <= 1'b0;
                done <= 1'b1;
                quot <= {q[W-2:0], ge};
                rem  <= ge ? r_sub[WD-1:0] : r_sh[WD-1:0];
            end
        end
    end
endmodule
