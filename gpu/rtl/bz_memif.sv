// =====================================================================================================
// bz_memif.sv — переходник памяти: ядро этапа A просит по одному слову, SDRAM отдаёт пачками по 8 слов.
// =====================================================================================================
//
// ПАЧКА (BURST)
//   SDRAM устроена так, что открыть строку памяти долго (несколько тактов), а потом слова идут по одному
//   за такт. Поэтому контроллер (sdram_burst) всегда читает и пишет пачками по 8 слов = 32 байта
//   подряд, выровненными на 32 байта. Чтение одного слова стоило бы почти столько же, сколько пачки.
//
// КЭШ СТРОК
//   Кэш — маленькая быстрая память, где лежат копии недавно прочитанного. Ядро часто читает соседние
//   байты (тексели одной строки текстуры, клетки lightmap) — второе чтение той же пачки берётся из кэша
//   за такт, без SDRAM. Здесь 16 «строк кэша» по 8 слов (одна пачка каждая). Какая строка кэша
//   отвечает за адрес, решают биты адреса [8:5] («прямое отображение»: у каждой пачки памяти ровно
//   одно место в кэше). Чтобы знать, какая именно пачка там лежит, рядом хранится «тег» — старшие биты
//   её адреса [22:9], и признак «строка заполнена» (lval).
//     чтение, тег совпал (попадание) — слово из кэша на следующем такте;
//     не совпал (промах) — пачка из SDRAM целиком в строку кэша, ядру — нужное слово из неё.
//
// ЗАПИСЬ «НАСКВОЗЬ»
//   Запись сразу идёт в SDRAM: пачка, в которой пишется одно слово, а 7 остальных закрыты маской DQM
//   (маска — какие байты слова писать; DQM — вывод SDRAM, запрещающий запись байта). Если эта пачка
//   есть в кэше, её строка кэша сбрасывается — иначе следующее чтение увидело бы старое; следующее
//   чтение просто возьмёт пачку из SDRAM заново.
//
// Это переходник для ядра этапа A (оно — образец и медленное). У конвейера этапа B свои клиенты SDRAM:
// куски z и цвета пачками, кэш текстур.
//
// ЭТАП B (bz_core2): ядро пишет через переходник только WRITE и читает таблицы SETUP; z и цвет пишет
// конвейер точки своими клиентами. Поэтому два входа:
//   inv       — такт «забыть кэш» (после слива конвейера: в кэше могли остаться старые z и цвет);
//   c_nocache — чтение мимо кэша, всегда из SDRAM. Это «забор»: мост держит порядок операций одного
//               клиента, поэтому ответ на такое чтение придёт, только когда все прежние записи ядра уже
//               в SDRAM, — после него конвейер может читать то, что ядро записало.
module bz_memif #(
    parameter int LB = 4                    // строк кэша — 2^LB (этап A — 16; этапу B хватает 2: таблицы SETUP
                                            // читаются подряд, а 16 строк — ~400 ячеек логики)
) (
    input  wire        clk,
    input  wire        rst_n,
    // порт ядра (bz_core): req держится до ack
    input  wire        c_req,
    input  wire        c_we,
    input  wire [22:0] c_addr,
    input  wire [31:0] c_wdata,
    input  wire [3:0]  c_be,
    input  wire        c_nocache,
    input  wire        inv,
    output reg         c_ack,
    output reg  [31:0] c_rdata,
    // клиент моста (сигналы уже отобраны по метке этого клиента)
    output reg         b_req,
    output reg         b_we,
    output reg  [20:0] b_addr,
    input  wire        b_ack,
    input  wire        b_wr_take,
    input  wire [5:0]  b_wr_idx,
    output wire [31:0] b_wdata,
    output wire [3:0]  b_wmask,
    input  wire        b_rd_valid,
    input  wire [5:0]  b_rd_idx,
    input  wire [31:0] b_rd_data
);
    localparam [2:0] M_IDLE = 0, M_RD_REQ = 1, M_RD_DATA = 2, M_WR_REQ = 3, M_WR_DATA = 4, M_DONE = 5;

    reg [2:0]  st;
    reg [31:0] lc [0:(8 << LB) - 1];    // строки кэша: {строка, слово[2:0]}
    reg [17-LB:0] ltag [0:(1 << LB) - 1];
    reg [(1 << LB) - 1:0] lval;
    reg [3:0]  cnt;
    reg [22:0] a;                   // адрес текущего запроса ядра
    reg [31:0] wd;
    reg [3:0]  be;

    wire [LB-1:0] line = a[4+LB:5];
    wire       hit  = lval[c_addr[4+LB:5]] && ltag[c_addr[4+LB:5]] == c_addr[22:5+LB];

    assign b_wdata = wd;
    assign b_wmask = (b_wr_idx[2:0] == a[4:2]) ? be : 4'b0000;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            st    <= M_IDLE;
            c_ack <= 1'b0;
            b_req <= 1'b0;
            lval  <= '0;
        end else begin
            c_ack <= 1'b0;
            case (st)
            M_IDLE:
                if (c_req) begin
                    a  <= c_addr;
                    wd <= c_wdata;
                    be <= c_be;
                    if (c_we) begin
                        b_req  <= 1'b1;
                        b_we   <= 1'b1;
                        b_addr <= {c_addr[22:5], 3'b000};
                        st     <= M_WR_REQ;
                    end else if (hit && !c_nocache) begin
                        c_rdata <= lc[{c_addr[4+LB:5], c_addr[4:2]}];
                        c_ack   <= 1'b1;
                        st      <= M_DONE;
                    end else begin
                        b_req  <= 1'b1;
                        b_we   <= 1'b0;
                        b_addr <= {c_addr[22:5], 3'b000};
                        st     <= M_RD_REQ;
                    end
                end
            M_RD_REQ:
                if (b_ack) begin
                    b_req <= 1'b0;
                    cnt   <= 4'd0;
                    lval[line] <= 1'b0;
                    st    <= M_RD_DATA;
                end
            M_RD_DATA:
                if (b_rd_valid) begin
                    lc[{line, b_rd_idx[2:0]}] <= b_rd_data;
                    if (b_rd_idx[2:0] == a[4:2])
                        c_rdata <= b_rd_data;
                    cnt <= cnt + 1'b1;
                    if (cnt == 4'd7) begin
                        ltag[line] <= a[22:5+LB];
                        lval[line] <= 1'b1;
                        c_ack      <= 1'b1;
                        st         <= M_DONE;
                    end
                end
            M_WR_REQ:
                if (b_ack) begin
                    b_req <= 1'b0;
                    cnt   <= 4'd0;
                    st    <= M_WR_DATA;
                end
            M_WR_DATA:
                if (b_wr_take) begin
                    cnt <= cnt + 1'b1;
                    if (cnt == 4'd7) begin
                        // Эта пачка есть в кэше — её копия устарела. Строку не правим, а сбрасываем:
                        // правка отдельных байт превращала кэш в тысячи триггеров (первая сборка Gowin:
                        // 4229 триггеров и 7372 LUT), а обычная память пишется только словами целиком.
                        if (lval[line] && ltag[line] == a[22:5+LB])
                            lval[line] <= 1'b0;
                        c_ack <= 1'b1;
                        st    <= M_DONE;
                    end
                end
            // такт после ответа: ядро снимает req на следующем фронте — тот же запрос не брать
            M_DONE:
                st <= M_IDLE;
            default:
                st <= M_IDLE;
            endcase
            if (inv)
                lval <= '0;
        end
    end
endmodule
