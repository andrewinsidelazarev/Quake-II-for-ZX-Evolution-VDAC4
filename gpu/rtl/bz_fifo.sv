// =====================================================================================================
// bz_fifo.sv — очередь команд «бомж-3D»: ESP пишет слова по LINK, ядро забирает их по одному.
// =====================================================================================================
//
// ЧТО ТАКОЕ FIFO
//   FIFO (First In — First Out, «первым пришёл — первым ушёл») — очередь. С одной стороны в неё кладут
//   слова (push), с другой забирают (pop) в том же порядке. Нужна она потому, что ESP присылает
//   команды пачками и быстро (слово за ~200 нс), а ядро тратит на одну команду то десяток тактов, то
//   тысячи (большой многоугольник). Очередь сглаживает разницу: ESP заранее узнаёт, сколько в ней
//   места (регистр FIFO_FREE), и не пишет больше.
//
// КАК УСТРОЕНА
//   Память на DEPTH слов (по умолчанию 2048 слов × 32 бита = 8 КБ, это 4 блока BSRAM — встроенной
//   блочной памяти ПЛИС, у GW2AR-18 таких 46 по 18 Кбит). Два указателя:
//     wp — куда писать следующее слово, rp — откуда читать следующее.
//   Указатели на разряд шире адреса: тогда «очередь полна» (wp − rp = DEPTH) и «очередь пуста»
//   (wp = rp) различаются — при равных младших разрядах смотрим на старший.
//
//   Чтение из BSRAM занимает такт: адрес подаётся на одном фронте, слово выходит на следующем.
//   Ядру же удобно, чтобы слово уже лежало на выходе, пока оно его не взяло («first word fall
//   through», FWFT). Поэтому на выходе регистр q с признаком q_valid: как только он пуст (или ядро
//   забирает слово в этом такте), в него подгружается следующее слово из памяти.
//
// Всё в одном домене тактирования (clk_mem): слова LINK уже переведены в него модулем fb_link.
module bz_fifo #(
    parameter int AW = 11                  // разрядов адреса: глубина 2^AW слов
) (
    input  wire          clk,
    input  wire          rst_n,
    // запись (сторона LINK)
    input  wire          push,             // такт: положить wdata
    input  wire [31:0]   wdata,
    output reg           overflow,         // липкий флаг: слово пришло в полную очередь и пропало
    // чтение (сторона ядра) — как у bz_core: valid/ready
    output reg  [31:0]   q,                // слово на выходе
    output reg           q_valid,          // на выходе есть слово
    input  wire          pop,              // ядро забирает q в этом такте (бывает только при q_valid)
    // сколько слов ещё можно положить (для ESP)
    output wire [AW:0]   free
);
    localparam int DEPTH = 1 << AW;

    reg [31:0] mem [0:DEPTH-1];            // сама очередь — синтезатор кладёт её в BSRAM
    reg [AW:0] wp, rp;                     // указатели на разряд шире адреса (см. выше)

    wire [AW:0] used  = wp - rp;           // слов в памяти (без слова в регистре q)
    wire        full  = used == DEPTH[AW:0];
    wire        empty = used == 0;
    // слово на выходе тоже занимает место очереди: ESP должна видеть общее число.
    // Снизу — ноль (24.11.2026): если ESP записала больше, чем было места (испорченное чтение FIFO_FREE),
    // память заполняется целиком при занятом q — слов DEPTH + 1, и разность уходила в −1 = 0xFFF
    // («4095 слов свободно» — ESP переполнила бы очередь снова). Так число монотонно от числа слов, а оно
    // за такт меняется не больше чем на 1 — на этом держится код Грея FIFO_FREE в bz_top.
    wire [AW+1:0] held = {1'b0, used} + {{(AW+1){1'b0}}, q_valid};     // слов всего: 0…DEPTH + 1
    assign free = held >= DEPTH[AW+1:0] ? '0 : DEPTH[AW:0] - held[AW:0];

    // подгрузить выход: регистр q пуст или освобождается в этом такте, а в памяти что-то есть
    wire load = !empty && (!q_valid || pop);

    always @(posedge clk) begin
        // запись в BSRAM — отдельным always без сброса: так синтезатор узнаёт блочную память
        if (push && !full)
            mem[wp[AW-1:0]] <= wdata;
        // чтение BSRAM тоже регистровое (фронт → слово), иначе память ушла бы в триггеры
        if (load)
            q <= mem[rp[AW-1:0]];
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            wp       <= '0;
            rp       <= '0;
            q_valid  <= 1'b0;
            overflow <= 1'b0;
        end else begin
            if (push) begin
                if (full)
                    overflow <= 1'b1;      // ESP нарушила договор о месте — запомним для STATUS
                else
                    wp <= wp + 1'b1;
            end
            if (load) begin
                rp      <= rp + 1'b1;
                q_valid <= 1'b1;
            end else if (pop)
                q_valid <= 1'b0;
        end
    end
endmodule
