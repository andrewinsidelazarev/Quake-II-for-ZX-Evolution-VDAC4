// =====================================================================================================
// bz_ram.sv — простая двухпортовая память: один порт пишет, другой читает (в ПЛИС — блок BSRAM).
// =====================================================================================================
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ
//   В ПЛИС Gowin есть готовые блоки памяти BSRAM по 18 Кбит (2 КБ). Синтезатор сам узнаёт их в коде,
//   если память описана «по образцу»: массив, запись по фронту такта, чтение — тоже по фронту, в
//   регистр. Здесь этот образец написан один раз, а конвейер точки (bz_pix) просто ставит нужные
//   экземпляры: кэш текстур, lightmap, colormap, таблицу волны.
//
// ЧТЕНИЕ «ПО ФРОНТУ» И РАЗРЕШЕНИЕ re
//   Адрес чтения ra защёлкивается фронтом такта, слово появляется на rd в следующем такте и
//   держится. Пока re = 0, ни адрес, ни слово не меняются — так конвейер «замораживает» ступень,
//   когда стоит (у блока BSRAM это вывод CE — clock enable).
//
// ЧТЕНИЕ И ЗАПИСЬ ОДНОГО АДРЕСА В ОДНОМ ТАКТЕ
//   Что прочтётся — старое или новое слово, — у блоков BSRAM не обещано. Схемы вокруг этой памяти так
//   не делают: кэш пишет строку, только пока ступень чтения стоит, загрузка lightmap пишет другой слот.
//
// ВЫХОДНОЙ РЕГИСТР (OREG = 1)
//   У блока BSRAM слово появляется на выходе поздно: ~2,3 нс после фронта (сборка этапа B 23.11), и
//   если дальше в том же такте сумматор и сравнения, такт 60,75 МГц не успевает. С OREG = 1 слово
//   проходит ещё через регистр (у блока он свой, «pipeline» — READ_MODE 1): rd — через ДВА такта
//   с re = 1 после адреса, зато выходит сразу после фронта. Оба регистра стоят при re = 0 — для
//   конвейера с общим «стопом» это просто ещё одна ступень.
module bz_ram #(
    parameter int AW = 10,                  // разрядов адреса: 2^AW слов
    parameter int DW = 32,                  // разрядов слова
    parameter bit OREG = 1'b0               // 1 — слово через выходной регистр (на такт позже)
) (
    input  wire          clk,
    input  wire          we,                // запись: wd → m[wa]
    input  wire [AW-1:0] wa,
    input  wire [DW-1:0] wd,
    input  wire          re,                // чтение: m[ra] → rd на следующем такте
    input  wire [AW-1:0] ra,
    output reg  [DW-1:0] rd
);
    reg [DW-1:0] m [0:(1 << AW) - 1];

    always @(posedge clk)
        if (we)
            m[wa] <= wd;
    generate if (OREG) begin : g_oreg
        reg [DW-1:0] q1;                    // слово по адресу прошлого такта с re = 1
        always @(posedge clk)
            if (re) begin
                q1 <= m[ra];
                rd <= q1;
            end
    end else begin : g_plain
        always @(posedge clk)
            if (re)
                rd <= m[ra];
    end endgenerate
endmodule
