// =====================================================================================================
// bz_div4.sv — быстрый делитель без знака: quot = floor(num / den), rem = num − quot·den.
// =====================================================================================================
//
// ЧЕМ ОТЛИЧАЕТСЯ ОТ bz_div
//   bz_div — «школьное» деление в столбик по одной двоичной цифре частного за такт, всегда W тактов
//   (48). Здесь два ускорения, результат тот же до бита:
//
//   1) RADIX-4 — две цифры за такт. В столбик по основанию 4: к остатку дописываем сразу 2 бита делимого
//      (r·4 + два бита) и спрашиваем, сколько раз влезает делитель: 0, 1, 2 или 3 раза. Для этого три
//      сравнения сразу — с d, 2d и 3d; цифра частного — сколько влезло, остаток — r·4 + биты − цифра·d.
//
//   2) БЕЗ ПУСТЫХ ШАГОВ. Пусть старшая единица делимого — бит mn, делителя — бит md. Частное тогда
//      короче делимого: в нём не больше q = mn − md + 1 цифр, а все цифры выше — заведомо нули (в столбик
//      это шаги, где «не влезает»). Поэтому старшие биты делимого сразу кладутся в остаток (num >> q — это
//      число меньше 2^md, то есть меньше делителя, остаток верный), и считаются только q последних цифр.
//      Примеры из растеризатора: край ребра — частное до 13 бит → 7 тактов; перспектива 2^46 / zi —
//      17…32 бит → 9…16 тактов (было 48 в обоих случаях).
//
// ПРОТОКОЛ — как у bz_div: start на такт (num, den защёлкиваются), через несколько тактов done на такт,
// quot и rem держатся до следующего start. den = 0 — недопустимо (ядро так не делит).
module bz_div4 #(
    parameter W  = 48,                      // разрядов делимого и частного
    parameter WD = 32,                      // разрядов делителя
    // FIXQ > 0 (чётное): вызывающий ручается, что частное меньше 2^FIXQ. Тогда выравнивание не нужно —
    // старшие биты делимого сразу в остаток (num >> FIXQ < den), шагов всегда FIXQ/2, и в схеме нет
    // сдвигателя на переменное число бит (он был самой дорогой частью: ~400 LUT на делитель).
    parameter FIXQ = 0
) (
    input  wire          clk,
    input  wire          rst,
    input  wire          start,
    input  wire [W-1:0]  num,
    input  wire [WD-1:0] den,
    output reg           busy,
    output reg           done,
    output reg  [W-1:0]  quot,
    output reg  [WD-1:0] rem
);
    // номер старшей единицы (−1 для нуля) — «приоритетный шифратор»
    function integer msb_w (input [W-1:0] v);
        integer i;
        begin
            msb_w = -1;
            for (i = 0; i < W; i = i + 1)
                if (v[i]) msb_w = i;
        end
    endfunction
    function integer msb_d (input [WD-1:0] v);
        integer i;
        begin
            msb_d = -1;
            for (i = 0; i < WD; i = i + 1)
                if (v[i]) msb_d = i;
        end
    endfunction

    reg [W-1:0]  q;                         // сверху — ещё не поданные биты делимого, снизу копится частное
    reg [WD+1:0] r;                         // остаток (на 2 бита шире делителя: r·4 + биты < 4·den)
    reg [WD-1:0] d;
    reg [5:0]    steps;                     // сколько шагов по 2 цифры осталось

    wire [WD+1:0] r4  = {r[WD-1:0], q[W-1:W-2]};        // r·4 + два следующих бита делимого
    wire [WD+2:0] d1  = {3'b000, d};
    wire [WD+2:0] d2  = {2'b00, d, 1'b0};
    wire [WD+2:0] d3  = d1 + d2;
    wire          ge3 = {1'b0, r4} >= d3;
    wire          ge2 = {1'b0, r4} >= d2;
    wire          ge1 = {1'b0, r4} >= d1;
    wire [1:0]    dig = ge3 ? 2'd3 : ge2 ? 2'd2 : ge1 ? 2'd1 : 2'd0;
    wire [WD+2:0] sub = ge3 ? d3 : ge2 ? d2 : ge1 ? d1 : '0;
    wire [WD+1:0] rn  = WD'({1'b0, r4} - sub);          // новый остаток (< den)

    always @(posedge clk) begin
        done <= 1'b0;
        if (rst) begin
            busy <= 1'b0;
        end else if (start && FIXQ > 0) begin
            r     <= (WD + 2)'(num >> FIXQ);
            q     <= num << (W - FIXQ);
            d     <= den;
            steps <= 6'(FIXQ / 2);
            busy  <= 1'b1;
        end else if (start) begin : setup
            integer mn, md, nq, sh;
            mn = msb_w (num);
            md = msb_d (den);
            nq = mn - md + 1;                       // цифр частного (двоичных); ≤ 0 — частное 0
            if (nq <= 0) begin
                // делимое меньше 2^md ≤ делителя... или равно по старшему биту — проверим честно
                quot <= '0;
                rem  <= num[WD-1:0];
                busy <= 1'b0;
                done <= 1'b1;
            end else begin
                if (nq[0]) nq = nq + 1;             // чётное число цифр: шаги по две
                // старшие биты делимого (их W − nq) — сразу в остаток: num >> nq < 2^md ≤ den
                r     <= (WD + 2)'(num >> nq);
                // оставшиеся nq бит — к верху q, чтобы на каждом шаге брать два старших
                sh = W - nq;
                q     <= num << sh;
                d     <= den;
                steps <= 6'(nq / 2);
                busy  <= 1'b1;
            end
        end else if (busy) begin
            r     <= rn;
            q     <= {q[W-3:0], dig};
            steps <= steps - 1'b1;
            if (steps == 6'd1) begin
                busy <= 1'b0;
                done <= 1'b1;
                quot <= {q[W-3:0], dig};
                rem  <= rn[WD-1:0];
            end
        end
    end
endmodule
